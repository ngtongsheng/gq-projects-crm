import { z } from "zod";
import { todayMyt } from "@/lib/format/date";
import { AccountType } from "../../customers/schemas";
import type { MofDraft } from "../mof-form";
import { JobScope, LineUnit, MofStage, StockType } from "../schemas";

export const mofRow = z.object({
  id: z.string(),
  mof_no: z.string(),
  loa_date: z.string(),
  salesperson_id: z.string(),
  second_salesperson_id: z.string().nullable(),
  project_id: z.string().nullable(),
  company_name: z.string(),
  project_name: z.string(),
  loa_no: z.string().nullable(),
  quote_no: z.string().nullable(),
  site_address: z.string().nullable(),
  site_contact_name: z.string().nullable(),
  site_contact_mobile: z.string().nullable(),
  office_pic_id: z.string().nullable(),
  customer_contact: z.string().nullable(),
  accounts_contact: z.string().nullable(),
  customer_name: z.string().nullable(),
  customer_mobile: z.string().nullable(),
  accounts_name: z.string().nullable(),
  accounts_mobile: z.string().nullable(),
  accounts_email: z.string().nullable(),
  scope: JobScope,
  installer_name: z.string().nullable(),
  contract_sum: z.number(),
  vo_amount: z.number(),
  retention_pct: z.number(),
  invoice_no: z.string().nullable(),
  invoice_date: z.string().nullable(),
  commission_type: AccountType,
  delivery_date: z.string().nullable(),
  stage: MofStage,
  latest_update: z.string().nullable(),
  payment_checked: z.boolean(),
  approvals_in_writing: z.boolean(),
  artwork_signed_off: z.boolean(),
  dos_pre_approved: z.boolean(),
  updated_at: z.string(),
  mof_lines: z.array(
    z.object({
      id: z.string(),
      product: z.string(),
      stock_type: StockType,
      supplier: z.string().nullable(),
      qty: z.number(),
      unit: LineUnit,
      area_m2: z.number(),
      created_at: z.string(),
    }),
  ),
});

/** A saved column that may be empty, as the form wants it: "" when null. */
export const blankIfNull = (value: string | null) => value ?? "";

export const blankDraft = (): MofDraft => ({
  id: "",
  mofNo: "",
  loaDate: todayMyt(),
  salespersonId: "",
  secondSalespersonId: "",
  projectId: "",
  companyName: "",
  projectName: "",
  loaNo: "",
  quoteNo: "",
  siteAddress: "",
  siteContactName: "",
  siteContactMobile: "",
  officePicId: "",
  customerContact: "",
  accountsContact: "",
  customerName: "",
  customerMobile: "",
  accountsName: "",
  accountsMobile: "",
  accountsEmail: "",
  scope: "s_and_l",
  installerName: "",
  contractSum: null,
  voAmount: 0,
  retentionPct: 0,
  invoiceNo: "",
  invoiceDate: "",
  commissionType: "own",
  deliveryDate: "",
  stage: "pending_order",
  latestUpdate: "",
  paymentChecked: false,
  approvalsInWriting: false,
  artworkSignedOff: false,
  dosPreApproved: false,
  lines: [],
});

export const draftFromMof = (row: z.infer<typeof mofRow>): MofDraft => ({
  id: row.id,
  mofNo: row.mof_no,
  loaDate: row.loa_date,
  salespersonId: row.salesperson_id,
  secondSalespersonId: blankIfNull(row.second_salesperson_id),
  projectId: blankIfNull(row.project_id),
  companyName: row.company_name,
  projectName: row.project_name,
  loaNo: blankIfNull(row.loa_no),
  quoteNo: blankIfNull(row.quote_no),
  siteAddress: blankIfNull(row.site_address),
  siteContactName: blankIfNull(row.site_contact_name),
  siteContactMobile: blankIfNull(row.site_contact_mobile),
  officePicId: blankIfNull(row.office_pic_id),
  customerContact: blankIfNull(row.customer_contact),
  accountsContact: blankIfNull(row.accounts_contact),
  customerName: blankIfNull(row.customer_name),
  customerMobile: blankIfNull(row.customer_mobile),
  accountsName: blankIfNull(row.accounts_name),
  accountsMobile: blankIfNull(row.accounts_mobile),
  accountsEmail: blankIfNull(row.accounts_email),
  scope: row.scope,
  installerName: blankIfNull(row.installer_name),
  contractSum: row.contract_sum,
  voAmount: row.vo_amount,
  retentionPct: row.retention_pct,
  invoiceNo: blankIfNull(row.invoice_no),
  invoiceDate: blankIfNull(row.invoice_date),
  commissionType: row.commission_type,
  deliveryDate: blankIfNull(row.delivery_date),
  stage: row.stage,
  latestUpdate: blankIfNull(row.latest_update),
  paymentChecked: row.payment_checked,
  approvalsInWriting: row.approvals_in_writing,
  artworkSignedOff: row.artwork_signed_off,
  dosPreApproved: row.dos_pre_approved,
  lines: [...row.mof_lines]
    .sort((a, b) => a.created_at.localeCompare(b.created_at))
    .map((line) => ({
      id: line.id,
      product: line.product,
      stockType: line.stock_type,
      supplier: blankIfNull(line.supplier),
      qty: String(line.qty),
      unit: line.unit,
      // Area units work the area out from qty; only rolls and pieces keep a keyed-in area.
      areaM2:
        line.unit === "roll" || line.unit === "pcs" ? String(line.area_m2) : "",
    })),
});
